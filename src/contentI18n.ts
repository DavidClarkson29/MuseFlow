export function localizeBuiltinText(value:unknown, lang:Lang):string {
  const raw=String(value ?? '')
  if(lang==='zh' || !raw)return raw
  if(/^未命名画板\s+\d+$/.test(raw))return raw.replace('未命名画板','Untitled Board')
  if(exact[raw])return exact[raw]
  let out=raw
  for(const [from,to] of phrases)out=out.split(from).join(to)
  for(const [from,to] of Object.entries(exact).sort((a,b)=>b[0].length-a[0].length))out=out.split(from).join(to)
  out=out.replace(/，/g,', ').replace(/。/g,'. ').replace(/；/g,'; ').replace(/：/g,': ')
  return exact[out] ?? out
}
